import { z } from "zod";

export const personalDetailsSchema = z.object({
  fullName: z.string().trim().max(160).default(""),
  professionalTitle: z.string().trim().max(180).default(""),
  email: z.union([z.email(), z.literal("")]).default(""),
  phone: z.string().trim().max(70).default(""),
  location: z.string().trim().max(180).default(""),
  linkedin: z.string().trim().max(400).default(""),
  website: z.string().trim().max(400).default(""),
  photo: z.string().max(80000).regex(/^(data:image\/(jpeg|png);base64,[A-Za-z0-9+/=]+)?$/).default(""),
});
export const resumeDesignSchema = z.object({
  accent: z.string().regex(/^#[0-9a-f]{6}$/i).default("#243d4b"),
  font: z.enum(["sans", "serif", "mono"]).default("sans"),
  fontSize: z.number().min(9).max(13).default(10),
  lineHeight: z.number().min(1.15).max(1.9).default(1.35),
  margin: z.number().min(28).max(65).default(32),
  pageSize: z.enum(["A4", "LETTER"]).default("A4"),
  headerAlign: z.enum(["left", "center"]).default("left"),
  sectionStyle: z.enum(["rule", "band", "minimal"]).default("rule"),
  onePage: z.boolean().default(true),
  layout: z.enum(["auto", "single", "sidebar-left", "sidebar-right"]).default("auto"),
  sidebarWidth: z.number().min(120).max(200).default(150),
  locale: z.enum(["en-IN", "en-GB", "en-US"]).default("en-IN"),
  dateFormat: z.enum(["original", "short", "long", "year"]).default("original"),
  nameSize: z.number().min(18).max(32).default(23),
  headingSize: z.number().min(10).max(16).default(11),
  headingCase: z.enum(["uppercase", "original"]).default("uppercase"),
  sectionSpacing: z.number().min(6).max(24).default(12),
  entrySpacing: z.number().min(1).max(12).default(4),
  headerSpacing: z.number().min(8).max(32).default(16),
  textColor: z.string().regex(/^#[0-9a-f]{6}$/i).default("#283243"),
  headingColor: z.string().regex(/^#[0-9a-f]{6}$/i).default("#243d4b"),
  boldEntries: z.boolean().default(true),
  showDates: z.boolean().default(true),
  datePosition: z.enum(["inline", "right"]).default("inline"),
  bulletStyle: z.enum(["disc", "dash"]).default("disc"),
  contactSeparator: z.enum(["dot", "bar", "stacked"]).default("dot"),
  showLinks: z.boolean().default(true),
  linkStyle: z.enum(["plain", "underline"]).default("plain"),
  showPhoto: z.boolean().default(false),
  photoSize: z.number().min(40).max(100).default(64),
  photoShape: z.enum(["round", "square"]).default("round"),
  footerText: z.string().trim().max(120).default(""),
  pageNumbers: z.boolean().default(false),
});
export type ResumePersonalDetails = z.infer<typeof personalDetailsSchema>;
export type ResumeDesign = z.infer<typeof resumeDesignSchema>;
export type ResumeRenderOptions = { template?: string; personalDetails?: Partial<ResumePersonalDetails>; design?: Partial<ResumeDesign> };
